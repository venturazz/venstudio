import { test } from "node:test";
import assert from "node:assert/strict";
import { buildProvenance, makerLine, pluginRowNote, PROVIDER_NAME_MAX, providerTermsIssues, resolveHermesMaker } from "./asset-plan.ts";
import { resolveHermesVoice } from "./router-media.ts";
import { parseImageReply } from "./image-result.ts";

const LIVE_REPLY =
  '{"status":"ok","provider":"9router","source":"cloudflare-9router","model":"cf/@cf/black-forest-labs/flux-2-klein-4b",' +
  '"image":{"type":"url","value":"http://hermes-files:8000/img/cloudflare_1.jpg","mimeType":"image/jpeg"}}';

test("resolveHermesMaker names the backend, not the plugin, when Hermes reports one", () => {
  const parsed = parseImageReply(LIVE_REPLY);
  assert.ok(parsed.ok);
  if (!parsed.ok) return;
  // Untrusted (no order set): the backend under its own unlisted name, never unlisted-9router.
  assert.deepEqual(resolveHermesMaker({ provider: parsed.provider, backend: parsed.backend }, []), {
    provider: "unlisted-cloudflare-9router",
    backend: "cloudflare-9router",
    plugin: "9router",
  });
  // Trusted: the owner listed the backend in HERMES_IMAGE_PROVIDER_ORDER.
  assert.equal(resolveHermesMaker({ provider: "9router", backend: "Canva" }, ["cloudflare", "canva"]).provider, "canva");
  assert.equal(resolveHermesMaker({ provider: "9router", backend: "canva" }, ["cloudflare"]).provider, "unlisted-canva");
});

test("resolveHermesMaker: listing the plugin vouches for nothing behind it", () => {
  assert.equal(resolveHermesMaker({ provider: "9router", backend: "agnes" }, ["9router"]).provider, "unlisted-agnes");
  // No backend report: always the plugin's unlisted name, even when the plugin is listed.
  assert.deepEqual(resolveHermesMaker({ provider: "9router", backend: "" }, ["9router"]), { provider: "unlisted-9router", backend: "", plugin: "9router" });
  assert.deepEqual(resolveHermesMaker({ provider: "9router" }, []), { provider: "unlisted-9router", backend: "", plugin: "9router" });
  // A source that is the plugin id itself says nothing about the backend.
  assert.equal(resolveHermesMaker({ provider: "9router", backend: "9router" }, ["9router"]).provider, "unlisted-9router");
  assert.equal(resolveHermesMaker({ provider: "", backend: "" }, []).provider, "unlisted-unknown");
  assert.equal(resolveHermesMaker({ provider: "", backend: "agnes" }, ["agnes"]).provider, "agnes");
  assert.ok(resolveHermesMaker({ provider: "9router", backend: "x".repeat(90) }, []).provider.length <= PROVIDER_NAME_MAX);
});

test("makerLine shows the backend, the plugin and the model", () => {
  assert.equal(
    makerLine("Image", { provider: "unlisted-cloudflare-9router", backend: "cloudflare-9router", plugin: "9router" }, "cf/@cf/black-forest-labs/flux-2-klein-4b"),
    "Image made by cloudflare-9router via 9router plugin (cf/@cf/black-forest-labs/flux-2-klein-4b)",
  );
  assert.equal(makerLine("Image", { provider: "canva", backend: "canva", plugin: "" }, ""), "Image made by canva");
  assert.equal(makerLine("Image", { provider: "unlisted-9router", backend: "", plugin: "9router" }, "m"), "Image made by unlisted-9router (m). Hermes did not say which backend made it");
});

test("licence text names the backend and keeps the plugin and model", () => {
  const img = buildProvenance({
    executor: "hermes-image",
    title: "shot-01",
    kind: "image",
    provider: "unlisted-cloudflare-9router",
    backend: "cloudflare-9router",
    plugin: "9router",
    model: "cf/@cf/black-forest-labs/flux-2-klein-4b",
  });
  assert.match(img.record.license, /^AI generated by cloudflare-9router \(cf\/@cf\/black-forest-labs\/flux-2-klein-4b\) through Hermes image_gen plugin 9router\. Commercial terms/);
  assert.equal(img.provider, "unlisted-cloudflare-9router");
  assert.equal(img.metadata.backend, "cloudflare-9router");
  assert.equal(img.metadata.plugin, "9router");
  const unknown = buildProvenance({ executor: "hermes-image", title: "s", kind: "image", provider: "unlisted-9router", plugin: "9router" });
  assert.match(unknown.record.license, /AI generated by unlisted-9router through Hermes image_gen plugin 9router\. Hermes did not say which backend made it\./);
  assert.equal(unknown.metadata.backend, undefined);
  const voice = buildProvenance({ executor: "hermes-capcut", title: "n", kind: "audio", provider: "unlisted-edge", backend: "edge", plugin: "capcut" });
  assert.match(voice.record.license, /^Voice made by edge through Hermes' CapCut workflow, plugin capcut\./);
});

test("a legacy plugin row covers only itself in the G-assets terms check", () => {
  const terms = [{ name: "unlisted-9router", kind: "image" as const, commercialOk: "yes" as const }];
  // Old assets saved under the plugin name pass on the owner's yes.
  assert.deepEqual(providerTermsIssues([{ title: "old", provider: "unlisted-9router", kind: "image" }], terms), []);
  // A backend behind the plugin is its own provider: the plugin row does not clear it.
  const issues = providerTermsIssues([{ title: "new", provider: "unlisted-canva", kind: "image" }], terms);
  assert.equal(issues.length, 1);
  assert.match(issues[0], /Confirm the commercial-use terms for unlisted-canva/);
});

test("pluginRowNote flags rows named after a plugin and nothing else", () => {
  assert.match(pluginRowNote("unlisted-9router", "image") ?? "", /names the Hermes plugin 9router, not the backend/);
  assert.equal(pluginRowNote("unlisted-canva", "image"), null);
  assert.equal(pluginRowNote("canva", "image"), null);
  assert.equal(pluginRowNote("unlisted-9router", "tts"), null);
});

test("resolveHermesVoice names the engine that spoke", () => {
  assert.deepEqual(resolveHermesVoice("capcut", { provider: "capcut", backend: "kokoro" }), { provider: "hermes-kokoro", backend: "kokoro", plugin: "capcut" });
  assert.deepEqual(resolveHermesVoice("capcut", { provider: "capcut", backend: "capcut" }), { provider: "capcut", backend: "capcut", plugin: "capcut" });
  assert.equal(resolveHermesVoice("capcut", { provider: "capcut", backend: "Edge" }).provider, "unlisted-edge");
  // No engine named: the CapCut plugin may have fallen through to anything.
  assert.equal(resolveHermesVoice("capcut", { provider: "capcut" }).provider, "unlisted-capcut");
  assert.equal(resolveHermesVoice("capcut", {}).provider, "unlisted-capcut");
  // The Kokoro request keeps its old rule without an engine report, and CapCut is never trusted there.
  assert.equal(resolveHermesVoice("kokoro", { provider: "kokoro" }).provider, "hermes-kokoro");
  assert.equal(resolveHermesVoice("kokoro", { provider: "foo" }).provider, "unlisted-foo");
  assert.equal(resolveHermesVoice("kokoro", { provider: "capcut", backend: "capcut" }).provider, "unlisted-capcut");
  assert.equal(resolveHermesVoice("kokoro", { provider: "9router", backend: "kokoro" }).provider, "hermes-kokoro");
});
