import { test } from "node:test";
import assert from "node:assert/strict";
import { bedNote, bedRefusal, MUSIC_TAG, pickMusicBed, type BedCandidate, type BedContext } from "./music-bed.ts";
import { defaultAssetPolicy } from "./templates.ts";
import { renderLicenseText } from "./production.ts";
import { buildAudioPlan } from "./audio-plan.ts";

const RUN = "11111111-1111-4111-8111-000000000001";
const CHANNEL = "22222222-2222-4222-8222-000000000001";
const NARRATION = "33333333-3333-4333-8333-000000000001";
const OLD_NARRATION = "33333333-3333-4333-8333-000000000002";

function track(over: Partial<BedCandidate> = {}): BedCandidate {
  return {
    id: "44444444-4444-4444-8444-000000000001",
    title: "Calm bed",
    kind: "audio",
    source: "upload",
    license: "Own composition, all rights",
    originUrl: "https://example.com/calm-bed",
    tags: [MUSIC_TAG],
    provider: "",
    providerKind: "",
    runId: null,
    channelId: null,
    hasFile: true,
    ...over,
  };
}

function ctx(over: Partial<BedContext> = {}): BedContext {
  return {
    template: { assetPolicy: defaultAssetPolicy(), audio: { musicPolicy: "self-or-licensed" } },
    runId: RUN,
    channelId: CHANNEL,
    narrationAssetIds: [NARRATION, OLD_NARRATION],
    providerTerms: [],
    ...over,
  };
}

test("the run's own narration is never the bed, even when it is the newest audio and somebody tagged it music", () => {
  // What the old query picked: the newest audio asset, which is the narration this run just recorded.
  const narration = track({ id: NARRATION, title: "Narration (kokoro)", source: "hermes", license: "Generated by kokoro", originUrl: "", provider: "kokoro", providerKind: "tts", runId: RUN, tags: [] });
  const testVoice = track({ id: "55555555-5555-4555-8555-000000000001", title: "Test voice", provider: "kokoro", providerKind: "tts", tags: [] });
  const music = track();
  assert.equal(pickMusicBed([narration, testVoice, music], ctx()).bed?.id, music.id);
  assert.equal(pickMusicBed([narration, testVoice], ctx()).bed, null, "no music in the library: no bed, never the voice");
  assert.equal(bedRefusal({ ...narration, tags: [MUSIC_TAG] }, ctx()), "it is speech, not music");
  assert.equal(bedRefusal({ ...music, id: OLD_NARRATION }, ctx()), "it is this video's narration", "an earlier voice attempt of this run");
  assert.equal(bedRefusal({ ...music, tags: [MUSIC_TAG, "narration"] }, ctx()), "it is speech, not music");
  // Narration and test voices carry no music tag, so they are not even listed as passed-over music.
  assert.deepEqual(pickMusicBed([narration, testVoice], ctx()).skipped, []);
});

test("only a tagged audio file with a stored file qualifies", () => {
  assert.equal(bedRefusal(track({ tags: [] }), ctx()), 'it is not tagged "music"');
  assert.equal(bedRefusal(track({ tags: ["Music"] }), ctx()), null, "tags are compared in lower case");
  assert.equal(bedRefusal(track({ kind: "image" }), ctx()), "it is not an audio file");
  assert.equal(bedRefusal(track({ hasFile: false }), ctx()), "the file was never stored");
});

test("the template's music policy and asset policy are respected", () => {
  const policy = (musicPolicy: BedContext["template"]["audio"]["musicPolicy"]) => ctx({ template: { assetPolicy: defaultAssetPolicy(), audio: { musicPolicy } } });
  assert.equal(bedRefusal(track(), policy("none")), "the template allows no music");
  assert.equal(pickMusicBed([track()], policy("none")).bed, null);
  assert.equal(bedRefusal(track({ source: "licensed" }), policy("licensed")), null);
  assert.equal(bedRefusal(track({ source: "generated", originUrl: "" }), policy("licensed")), "the template takes licensed music, and this is a generated file");
  assert.equal(bedRefusal(track({ source: "licensed" }), policy("self-generated")), "the template takes self-generated music, and this is a licensed file");
  assert.equal(bedRefusal(track(), policy("self-generated")), null, "an upload is the owner's own file");
  const noUploads = ctx({ template: { assetPolicy: { allowedSources: ["licensed"], forbidKinds: [] }, audio: { musicPolicy: "self-or-licensed" } } });
  assert.equal(bedRefusal(track(), noUploads), "source upload is not allowed in this template");
  const noAudio = ctx({ template: { assetPolicy: { allowedSources: ["upload"], forbidKinds: ["audio"] }, audio: { musicPolicy: "self-or-licensed" } } });
  assert.equal(bedRefusal(track(), noAudio), "the template allows no audio assets");
});

test("provenance has to be complete for publishing, as for every other input", () => {
  assert.equal(bedRefusal(track({ license: "  " }), ctx()), "no licence or permission note");
  assert.equal(bedRefusal(track({ originUrl: "" }), ctx()), "say where it came from (add an origin link)");
  assert.equal(bedRefusal(track({ source: "licensed", originUrl: "" }), ctx()), "say where it came from (add an origin link)");
});

test("a provider's track plays only once the owner confirmed its terms; unknown and no both refuse", () => {
  const made = track({ source: "generated", originUrl: "", provider: "suno", providerKind: "library", license: "Generated by suno" });
  assert.equal(bedRefusal(made, ctx()), "the commercial-use terms of suno are not confirmed in Settings");
  assert.equal(bedRefusal(made, ctx({ providerTerms: [{ name: "suno", kind: "library", commercialOk: "no", note: "" }] })), "the commercial-use terms of suno are not confirmed in Settings");
  assert.equal(bedRefusal(made, ctx({ providerTerms: [{ name: "suno", kind: "library", commercialOk: "yes", note: "" }] })), null);
  // Terms for the provider's images do not cover its music.
  assert.equal(bedRefusal(made, ctx({ providerTerms: [{ name: "suno", kind: "image", commercialOk: "yes", note: "" }] })) !== null, true);
});

test("the run's channel's own track beats a shared one; another channel's never plays; newest first among equals", () => {
  const shared = track({ id: "44444444-4444-4444-8444-0000000000a1", title: "Shared" });
  const own = track({ id: "44444444-4444-4444-8444-0000000000a2", title: "Own", channelId: CHANNEL });
  const other = track({ id: "44444444-4444-4444-8444-0000000000a3", title: "Other", channelId: "22222222-2222-4222-8222-0000000000ff" });
  assert.equal(pickMusicBed([shared, own], ctx()).bed?.title, "Own");
  assert.equal(pickMusicBed([other, shared], ctx()).bed?.title, "Shared");
  assert.equal(bedRefusal(other, ctx()), "it belongs to another channel");
  const newer = track({ id: "44444444-4444-4444-8444-0000000000a4", title: "Newer" });
  assert.equal(pickMusicBed([newer, shared], ctx()).bed?.title, "Newer");
  assert.equal(pickMusicBed([shared], ctx({ channelId: null })).bed?.title, "Shared");
});

test("the run says which track plays, or why none does", () => {
  const pick = pickMusicBed([track({ title: "No licence", license: "" }), track({ title: "Calm bed" })], ctx());
  assert.equal(bedNote(pick, "self-or-licensed"), "Music bed: Calm bed (Own composition, all rights).");
  const none = pickMusicBed([track({ title: "No licence", license: "" })], ctx());
  assert.equal(bedNote(none, "self-or-licensed"), "No music bed: no track qualifies (No licence: no licence or permission note). The mix is the narration and ambience.");
  assert.match(bedNote(pickMusicBed([], ctx()), "self-or-licensed"), /no audio in Assets is marked as a music track/);
  assert.equal(bedNote(pickMusicBed([], ctx()), "none"), "No music: the template allows none.");
});

test("no music gives bed null and a mix of narration and ambience; a known-long track is trimmed, else looped", () => {
  const plan = (bed: { assetId: string; durationSec?: number } | null) =>
    buildAudioPlan({ policy: "self-or-licensed", narrated: true, durationSec: 60, bed });
  const none = plan(null);
  assert.ok(none.ok && none.plan.bed === null && none.plan.ambient !== null);
  const long = plan({ assetId: "a", durationSec: 90 });
  assert.ok(long.ok && long.plan.bed?.cover === "trim");
  const unknown = plan({ assetId: "a" });
  assert.ok(unknown.ok && unknown.plan.bed?.cover === "loop");
});

test("the render's licence names the bed's maker and licence first, however many pictures it has", () => {
  const pictures = Array.from({ length: 600 }, (_, i) => ({ title: `shot-${i + 1}`, provider: "cloudflare", license: "AI generated by cloudflare (flux-1-schnell)" }));
  const text = renderLicenseText([
    ...pictures,
    { title: "Calm bed", provider: "", license: "Own composition, all rights", source: "upload", originUrl: "https://example.com/calm-bed", role: "Music bed" },
  ]);
  assert.ok(text.startsWith("Own render made with VenStudio from these inputs. Music bed: Calm bed (uploaded from https://example.com/calm-bed): Own composition, all rights"), text.slice(0, 200));
  assert.ok(text.length <= 1800);
  // Inputs without a role keep their order and wording; a licensed file without a provider names its origin.
  assert.equal(
    renderLicenseText([{ title: "Font", provider: "", license: "OFL", source: "licensed", originUrl: "https://fonts.example/inter" }, { title: "shot-01", provider: "cloudflare", license: "AI generated" }]),
    "Own render made with VenStudio from these inputs. Font (licensed from https://fonts.example/inter): OFL shot-01 (cloudflare): AI generated",
  );
});
